export const translateKey = (
  lang: SupportedLang,
  key: string,
  options?: Record<string, unknown>,
  defaultMessage?: string
): string => {
  const template = translations[lang][key] ?? defaultMessage ?? key;
  if (!options) return template;
  return Object.entries(options).reduce((acc, [k, v]) => acc.replaceAll(`{${k}}`, `${v}`), template);
};
